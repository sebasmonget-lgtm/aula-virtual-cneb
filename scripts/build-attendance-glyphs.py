"""Generate the tiny Poppins outline subset used by server-side attendance charts.

Usage: python scripts/build-attendance-glyphs.py Poppins-Bold.ttf Poppins-Regular.ttf
Requires fontTools for this development step only. Source: Google Fonts Poppins;
SIL Open Font License is retained in assets/templates/Poppins-OFL.txt.
"""
import json,sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen

def glyphs(file,characters):
 font=TTFont(file);cmap=font.getBestCmap();glyph_set=font.getGlyphSet();result={}
 for char in characters:
  name=cmap[ord(char)];pen=SVGPathPen(glyph_set);glyph_set[name].draw(pen)
  result[char]={'advance':font['hmtx'][name][0],'path':pen.getCommands()}
 return {'units':font['head'].unitsPerEm,'glyphs':result}

bold=glyphs(sys.argv[1],'0123456789');regular=glyphs(sys.argv[2],sorted(set('días de clase registrados')))
source="""// Generated by scripts/build-attendance-glyphs.py from Poppins (SIL OFL).
// Only ten digits and two fixed captions; no runtime font lookup or font service.
const bold=__BOLD__;
const regular=__REGULAR__;
function paths(value,font,size,x,y){
 const letters=Array.from(value),width=letters.reduce((sum,char)=>sum+font.glyphs[char].advance,0);let cursor=0;
 const drawing=letters.map(char=>{const glyph=font.glyphs[char],position=cursor;cursor+=glyph.advance;return glyph.path?`<path transform="translate(${position} 0)" d="${glyph.path}"/>`:'';}).join('');
 return `<g transform="translate(${x} ${y}) scale(${size/font.units} ${-size/font.units}) translate(${-width/2} 0)">${drawing}</g>`;
}
export function attendanceCenterPaths(recorded,pending){
 return `<g fill="#173352" data-total="${recorded}">${paths(String(recorded),bold,32,100,101)}</g><g fill="#456078">${paths(pending?'días registrados':'días de clase',regular,10,100,123)}</g>`;
}
""".replace('__BOLD__',json.dumps(bold,separators=(',',':'),ensure_ascii=False)).replace('__REGULAR__',json.dumps(regular,separators=(',',':'),ensure_ascii=False))
Path('src/lib/family-attendance-glyphs.mjs').write_text(source,encoding='utf-8')
